package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
)

type observability struct {
	Metrics struct {
		Description string `json:"description"`
		Labels      []struct {
			Name string `json:"name"`
			Doc  string `json:"doc"`
		} `json:"labels"`
		Metrics []struct {
			Name   string   `json:"name"`
			Kind   string   `json:"kind"`
			Unit   string   `json:"unit"`
			Labels []string `json:"labels"`
			Doc    string   `json:"doc"`
		} `json:"metrics"`
	}
	Tracing struct {
		Description string `json:"description"`
		MetadataKey struct {
			Name string `json:"name"`
			Doc  string `json:"doc"`
		} `json:"metadata_key"`
		Spans []struct {
			ID         string   `json:"id"`
			Name       string   `json:"name"`
			Kind       string   `json:"kind"`
			Attributes []string `json:"attributes"`
			Outcomes   []string `json:"outcomes"`
			Doc        string   `json:"doc"`
		} `json:"spans"`
		Attributes []struct {
			ID   string `json:"id"`
			Name string `json:"name"`
			Type string `json:"type"`
			Doc  string `json:"doc"`
		} `json:"attributes"`
	}
	outcomes []string
}

func loadObservability(root string) (*observability, error) {
	var o observability
	for file, into := range map[string]any{"metrics.json": &o.Metrics, "tracing.json": &o.Tracing} {
		raw, err := os.ReadFile(filepath.Join(root, "observability", file))
		if err != nil {
			return nil, err
		}
		dec := json.NewDecoder(bytes.NewReader(raw))
		dec.DisallowUnknownFields()
		if err := dec.Decode(into); err != nil {
			return nil, fmt.Errorf("%s: %w", file, err)
		}
	}
	labels := map[string]bool{}
	for _, l := range o.Metrics.Labels {
		if l.Name == "" || l.Doc == "" || labels[l.Name] {
			return nil, fmt.Errorf("label %q: needs a unique name and a doc", l.Name)
		}
		labels[l.Name] = true
	}
	seen := map[string]bool{}
	for _, m := range o.Metrics.Metrics {
		if m.Name == "" || m.Doc == "" || m.Unit == "" || seen[m.Name] {
			return nil, fmt.Errorf("metric %q: needs a unique name, a unit and a doc", m.Name)
		}
		seen[m.Name] = true
		if !slices.Contains([]string{"counter", "histogram", "gauge"}, m.Kind) {
			return nil, fmt.Errorf("metric %q: unknown kind %q", m.Name, m.Kind)
		}
		for _, l := range m.Labels {
			if !labels[l] {
				return nil, fmt.Errorf("metric %q: unknown label %q", m.Name, l)
			}
		}
	}
	if o.Tracing.MetadataKey.Name == "" {
		return nil, fmt.Errorf("tracing.json: metadata_key needs a name")
	}
	attrs := map[string]bool{}
	for _, a := range o.Tracing.Attributes {
		if a.ID == "" || a.Name == "" || a.Doc == "" || attrs[a.ID] || !slices.Contains([]string{"string", "int"}, a.Type) {
			return nil, fmt.Errorf("attribute %q: needs a unique id, a name, a doc and type string or int", a.ID)
		}
		attrs[a.ID] = true
	}
	spans := map[string]bool{}
	for _, s := range o.Tracing.Spans {
		if s.ID == "" || s.Name == "" || s.Doc == "" || spans[s.ID] || len(s.Outcomes) == 0 {
			return nil, fmt.Errorf("span %q: needs a unique id, a name, a doc and outcomes", s.ID)
		}
		spans[s.ID] = true
		if !slices.Contains([]string{"producer", "consumer", "internal"}, s.Kind) {
			return nil, fmt.Errorf("span %q: unknown kind %q", s.ID, s.Kind)
		}
		for _, a := range s.Attributes {
			if !attrs[a] {
				return nil, fmt.Errorf("span %q: unknown attribute %q", s.ID, a)
			}
		}
		for _, oc := range s.Outcomes {
			if !slices.Contains(o.outcomes, oc) {
				o.outcomes = append(o.outcomes, oc)
			}
		}
	}
	return &o, nil
}

const observabilityHeader = "Code generated by runnerq-spec tools/gen from observability/. DO NOT EDIT."

func goObservability(o *observability, pkg string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\npackage %s\n\n", observabilityHeader, pkg)

	b.WriteString("// Metric names (runnerq-spec observability/metrics.json).\nconst (\n")
	for _, m := range o.Metrics.Metrics {
		writeComment(&b, "\t", "// ", fmt.Sprintf("Metric%s is a %s (%s): %s", goName(m.Name), m.Kind, m.Unit, lowerFirst(m.Doc)))
		fmt.Fprintf(&b, "\tMetric%s = %q\n", goName(m.Name), m.Name)
	}
	b.WriteString(")\n\n// Metric label names.\nconst (\n")
	for _, l := range o.Metrics.Labels {
		writeComment(&b, "\t", "// ", fmt.Sprintf("Label%s: %s", goName(l.Name), l.Doc))
		fmt.Fprintf(&b, "\tLabel%s = %q\n", goName(l.Name), l.Name)
	}
	b.WriteString(")\n\n")
	b.WriteString("// MetricKind is how a metric aggregates.\ntype MetricKind string\n\nconst (\n\tMetricCounter   MetricKind = \"counter\"\n\tMetricHistogram MetricKind = \"histogram\"\n\tMetricGauge     MetricKind = \"gauge\"\n)\n\n")
	b.WriteString("// MetricInfo describes one metric of MetricCatalog.\ntype MetricInfo struct {\n\tName        string\n\tKind        MetricKind\n\t// Unit is UCUM: \"s\" for seconds, \"{activity}\" for a count of activities.\n\tUnit        string\n\tLabels      []string\n\tDescription string\n}\n\n")
	b.WriteString("// MetricCatalog lists every metric the SDK emits, in the spec's order.\nvar MetricCatalog = []MetricInfo{\n")
	kinds := map[string]string{"counter": "MetricCounter", "histogram": "MetricHistogram", "gauge": "MetricGauge"}
	for _, m := range o.Metrics.Metrics {
		labels := make([]string, len(m.Labels))
		for i, l := range m.Labels {
			labels[i] = "Label" + goName(l)
		}
		fmt.Fprintf(&b, "\t{Name: Metric%s, Kind: %s, Unit: %q, Labels: []string{%s}, Description: %q},\n",
			goName(m.Name), kinds[m.Kind], m.Unit, joinComma(labels), m.Doc)
	}
	b.WriteString("}\n\n")

	writeComment(&b, "", "// ", "MetadataTraceparent is "+lowerFirst(o.Tracing.MetadataKey.Doc))
	fmt.Fprintf(&b, "const MetadataTraceparent = %q\n\n", o.Tracing.MetadataKey.Name)
	b.WriteString("// Span names (runnerq-spec observability/tracing.json).\nconst (\n")
	for _, s := range o.Tracing.Spans {
		writeComment(&b, "\t", "// ", fmt.Sprintf("Span%s (%s): %s", goName(s.ID), s.Kind, s.Doc))
		fmt.Fprintf(&b, "\tSpan%s = %q\n", goName(s.ID), s.Name)
	}
	b.WriteString(")\n\n// Span attribute keys.\nconst (\n")
	for _, a := range o.Tracing.Attributes {
		writeComment(&b, "\t", "// ", fmt.Sprintf("Attr%s (%s): %s", goName(a.ID), a.Type, a.Doc))
		fmt.Fprintf(&b, "\tAttr%s = %q\n", goName(a.ID), a.Name)
	}
	b.WriteString(")\n\n// Span outcomes, the values of AttrOutcome.\nconst (\n")
	for _, oc := range o.outcomes {
		fmt.Fprintf(&b, "\tOutcome%s = %q\n", goName(oc), oc)
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

func tsObservability(o *observability) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\n", observabilityHeader)
	b.WriteString("/** Metric names (runnerq-spec observability/metrics.json). */\nexport const metricNames = {\n")
	for _, m := range o.Metrics.Metrics {
		writeJSDoc(&b, "  ", fmt.Sprintf("A %s (%s): %s", m.Kind, m.Unit, lowerFirst(m.Doc)))
		fmt.Fprintf(&b, "  %s: %s,\n", tsName(m.Name), quoteTS(m.Name))
	}
	b.WriteString("} as const;\n\n/** Metric label names. */\nexport const metricLabels = {\n")
	for _, l := range o.Metrics.Labels {
		writeJSDoc(&b, "  ", l.Doc)
		fmt.Fprintf(&b, "  %s: %s,\n", tsName(l.Name), quoteTS(l.Name))
	}
	b.WriteString("} as const;\n\n")
	b.WriteString("export type MetricName = (typeof metricNames)[keyof typeof metricNames];\n\n")
	b.WriteString("/** One metric of `metricCatalog`. */\nexport interface MetricInfo {\n  readonly name: MetricName;\n  readonly kind: \"counter\" | \"histogram\" | \"gauge\";\n  /** UCUM: \"s\" for seconds, \"{activity}\" for a count of activities. */\n  readonly unit: string;\n  readonly labels: readonly string[];\n  readonly description: string;\n}\n\n")
	b.WriteString("/** Every metric the SDK emits, in the spec's order. */\nexport const metricCatalog: readonly MetricInfo[] = [\n")
	for _, m := range o.Metrics.Metrics {
		labels := make([]string, len(m.Labels))
		for i, l := range m.Labels {
			labels[i] = quoteTS(l)
		}
		description := "    description: " + quoteTS(m.Doc) + ","
		if len(description) > 80 {
			description = "    description:\n      " + quoteTS(m.Doc) + ","
		}
		fmt.Fprintf(&b, "  {\n    name: %s,\n    kind: %s,\n    unit: %s,\n    labels: [%s],\n%s\n  },\n",
			quoteTS(m.Name), quoteTS(m.Kind), quoteTS(m.Unit), joinComma(labels), description)
	}
	b.WriteString("];\n\n")
	writeJSDoc(&b, "", "The activity metadata key holding the traceparent: "+lowerFirst(o.Tracing.MetadataKey.Doc))
	fmt.Fprintf(&b, "export const traceparentKey = %s;\n\n", quoteTS(o.Tracing.MetadataKey.Name))
	b.WriteString("/** Span names (runnerq-spec observability/tracing.json). */\nexport const spanNames = {\n")
	for _, s := range o.Tracing.Spans {
		writeJSDoc(&b, "  ", fmt.Sprintf("(%s) %s", s.Kind, s.Doc))
		fmt.Fprintf(&b, "  %s: %s,\n", tsName(s.ID), quoteTS(s.Name))
	}
	b.WriteString("} as const;\n\n/** Span attribute keys. */\nexport const spanAttributes = {\n")
	for _, a := range o.Tracing.Attributes {
		writeJSDoc(&b, "  ", fmt.Sprintf("(%s) %s", a.Type, a.Doc))
		fmt.Fprintf(&b, "  %s: %s,\n", tsName(a.ID), quoteTS(a.Name))
	}
	b.WriteString("} as const;\n\n/** Span outcomes, the values of `spanAttributes.outcome`. */\nexport const spanOutcomes = {\n")
	for _, oc := range o.outcomes {
		fmt.Fprintf(&b, "  %s: %s,\n", tsName(oc), quoteTS(oc))
	}
	b.WriteString("} as const;\n")
	return b.Bytes(), nil
}

func joinComma(items []string) string {
	var b bytes.Buffer
	for i, s := range items {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(s)
	}
	return b.String()
}
