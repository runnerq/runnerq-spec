// protocolDoc is a protocol's JSON Schema: $defs plus, for the storage
// protocol, x-operations.
type protocolDoc struct {
	file    string
	version string
	defs    *node
	ops     []*node
	// msgs are the conductor protocol's x-messages.
	msgs []*node
	// omitOptional: optional properties are omitempty in Go (absent, never
	// zero or null); optional object references are pointers.
	omitOptional bool
	// errorCodes are the ErrorCode enum's names, in kind-number order.
	errorCodes []string
}

func loadProtocol(root, rel string) (*protocolDoc, error) {
	raw, err := os.ReadFile(filepath.Join(root, rel))
	if err != nil {
		return nil, err
	}
	n, err := parseNode(raw)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", rel, err)
	}
	p := &protocolDoc{file: rel, defs: n.get("$defs")}
	if v, ok := n.num("x-version"); ok {
		p.version = v.String()
	}
	if p.defs == nil || p.version == "" {
		return nil, fmt.Errorf("%s: needs $defs and x-version", rel)
	}
	p.msgs = n.get("x-messages").itemsOrNil()
	p.omitOptional = n.flag("x-go-omit-optional")
	for _, m := range p.msgs {
		for _, key := range []string{"data", "response"} {
			if ref := m.str(key); ref != "" && p.defs.get(strings.TrimPrefix(ref, "#/$defs/")) == nil {
				return nil, fmt.Errorf("%s: message %s: unknown %s %s", rel, m.str("type"), key, ref)
			}
		}
		if m.str("type") == "" || m.str("data") == "" {
			return nil, fmt.Errorf("%s: a message needs a type and data", rel)
		}
	}
	p.ops = n.get("x-operations").itemsOrNil()
	if codes := p.defs.get("ErrorCode"); codes != nil && p.ops != nil {
		p.errorCodes = codes.strings("enum")
		// The wire names are the storage error kinds', in their numbering.
		s, err := load(root)
		if err != nil {
			return nil, err
		}
		for _, e := range s.Enums {
			if e.Name != "storage_error_kind" {
				continue
			}
			if len(e.Values) != len(p.errorCodes) {
				return nil, fmt.Errorf("%s: ErrorCode has %d codes, constants.json %d kinds", rel, len(p.errorCodes), len(e.Values))
			}
			for _, v := range e.Values {
				if v.Value >= len(p.errorCodes) || p.errorCodes[v.Value] != v.Name {
					return nil, fmt.Errorf("%s: ErrorCode differs from storage_error_kind at %s", rel, v.Name)
				}
			}
		}
	}
	for _, op := range p.ops {
		if op.str("name") == "" || p.defs.get(strings.TrimPrefix(op.str("args"), "#/$defs/")) == nil || op.get("result") == nil {
			return nil, fmt.Errorf("%s: operation %q needs a name, args and result", rel, op.str("name"))
		}
	}
	return p, nil
}

func (p *protocolDoc) def(name string) *node { return p.defs.get(name) }

func (p *protocolDoc) argsName(op *node) string {
	return strings.TrimPrefix(op.str("args"), "#/$defs/")
}

func (p *protocolDoc) header() string {
	return "// Code generated by runnerq-spec tools/gen from " + p.file + ". DO NOT EDIT.\n\n"
}

var goInitialisms = map[string]string{"id": "ID", "ms": "MS", "sdk": "SDK", "json": "JSON", "url": "URL", "ids": "IDs"}

// goField is a property's Go field name: x-go-name, else snake_case in
// PascalCase with initialisms, else the name with its first letter upper.
func goField(prop string, s *node) string {
	if name := s.str("x-go-name"); name != "" {
		return name
	}
	if strings.Contains(prop, "_") || prop == strings.ToLower(prop) {
		var b strings.Builder
		for _, w := range strings.Split(prop, "_") {
			if up, ok := goInitialisms[w]; ok {
				b.WriteString(up)
			} else if w != "" {
				b.WriteString(strings.ToUpper(w[:1]) + w[1:])
			}
		}
		return b.String()
	}
	return strings.ToUpper(prop[:1]) + prop[1:]
}

// goType is the Go type a schema maps to.
func (p *protocolDoc) goType(s *node) string {
	if t := s.str("x-go-type"); t != "" && s.get("$ref") == nil {
		if s.flag("x-go-pointer") {
			t = "*" + t
		}
		return t
	}
	if ref := s.refName(); ref != "" {
		d := p.def(ref)
		t := d.str("x-go-type")
		if t == "" {
			t = ref
		}
		if s.flag("x-go-pointer") {
			t = "*" + t
		}
		return t
	}
	if inner := s.nonNull(); inner != nil {
		t := p.goType(inner)
		if strings.HasPrefix(t, "[]") || strings.HasPrefix(t, "map[") || t == "json.RawMessage" {
			return t
		}
		return "*" + t
	}
	t := ""
	switch s.str("type") {
	case "string":
		t = "string"
	case "boolean":
		t = "bool"
	case "number":
		t = "float64"
	case "integer":
		t = "int64"
	case "array":
		t = "[]" + p.goType(s.get("items"))
	case "object":
		if ap := s.get("additionalProperties"); ap != nil && ap.isObj {
			t = "map[string]" + p.goType(ap)
		} else if ap != nil && ap.value == true {
			t = "map[string]any"
		}
	}
	if t == "" {
		panic(fmt.Sprintf("%s: no Go type for schema", p.file))
	}
	if s.flag("x-go-pointer") {
		t = "*" + t
	}
	return t
}

func goImports(src string, extra ...string) string {
	var imports []string
	for _, imp := range []struct{ use, path string }{
		{"context.", `"context"`},
		{"json.", `"encoding/json"`},
		{"time.", `"time"`},
		{"uuid.", `"github.com/google/uuid"`},
	} {
		if regexp.MustCompile(`\b` + regexp.QuoteMeta(imp.use) + `[A-Z]`).MatchString(src) {
			imports = append(imports, imp.path)
		}
	}
	for _, e := range extra {
		if e != "" {
			imports = append(imports, e)
		}
	}
	if len(imports) == 0 {
		return ""
	}
	return "import (\n" + strings.Join(imports, "\n") + "\n)\n\n"
}

// goStructs writes a Go struct per object definition that has no
// x-go-type (those are declared elsewhere).
func (p *protocolDoc) goStructs(b *bytes.Buffer, names []string) {
	for _, name := range names {
		d := p.def(name)
		if desc := d.str("description"); desc != "" {
			writeComment(b, "", "// ", name+" is "+lowerFirst(desc))
		} else if strings.HasSuffix(name, "Args") {
			fmt.Fprintf(b, "// %s are %s's arguments.\n", name, strings.TrimSuffix(name, "Args"))
		}
		props := d.get("properties")
		if props == nil || len(props.members) == 0 {
			fmt.Fprintf(b, "type %s struct{}\n\n", name)
			continue
		}
		fmt.Fprintf(b, "type %s struct {\n", name)
		required := d.strings("required")
		for _, m := range props.members {
			if desc := m.val.str("description"); desc != "" {
				writeComment(b, "\t", "// ", desc)
			}
			tag, typ := m.key, p.goType(m.val)
			optional := p.omitOptional && !slices.Contains(required, m.key)
			if m.val.flag("x-omitempty") || optional {
				tag += ",omitempty"
			}
			if optional && !strings.HasPrefix(typ, "*") && p.isObjectRef(m.val) {
				typ = "*" + typ
			}
			fmt.Fprintf(b, "\t%s %s `json:%q`\n", goField(m.key, m.val), typ, tag)
		}
		b.WriteString("}\n\n")
	}
}

// generatedDefs are the object definitions without x-go-type, in order.
func (p *protocolDoc) generatedDefs(filter func(string) bool) []string {
	var names []string
	for _, m := range p.defs.members {
		if m.val.str("type") == "object" && m.val.get("properties") != nil && m.val.str("x-go-type") == "" && filter(m.key) {
			names = append(names, m.key)
		}
	}
	return names
}

// goProtocol is the storage protocol's wire types: Version, the operations'
// argument structs and the error codes.
func goProtocol(p *protocolDoc, pkg, storageImport string) ([]byte, error) {
	var body bytes.Buffer
	fmt.Fprintf(&body, "// Version is the RunnerQ-Storage-Version header's value.\nconst Version = %q\n\n", p.version)
	p.goStructs(&body, p.generatedDefs(func(name string) bool { return strings.HasSuffix(name, "Args") }))
	body.WriteString("// NewArgs returns a pointer to a new zero value of operation's arguments,\n// or nil for an unknown operation.\nfunc NewArgs(operation string) any {\n\tswitch operation {\n")
	for _, op := range p.ops {
		fmt.Fprintf(&body, "\tcase %q:\n\t\treturn new(%s)\n", op.str("name"), p.argsName(op))
	}
	body.WriteString("\t}\n\treturn nil\n}\n\n")
	if len(p.errorCodes) > 0 {
		body.WriteString("// ErrorCodes are the wire codes of the storage error kinds, indexed by kind\n// number (storage.StorageErrorKind).\nvar ErrorCodes = [...]string{\n")
		for _, c := range p.errorCodes {
			fmt.Fprintf(&body, "\t%q,\n", c)
		}
		body.WriteString("}\n")
	}
	return goFile(p, pkg, body.String(), storageImport)
}

// goTypes is the object definitions reachable from roots (all, when none
// are given) as Go structs, and the enums among them as typed strings.
func goTypes(p *protocolDoc, pkg string, roots ...string) ([]byte, error) {
	var body bytes.Buffer
	keep := p.reachable(roots)
	p.goEnums(&body, keep)
	p.goStructs(&body, p.generatedDefs(keep))
	return goFile(p, pkg, body.String(), "")
}

// reachable reports which definitions roots refer to, directly or not;
// with no roots, every definition.
func (p *protocolDoc) reachable(roots []string) func(string) bool {
	if len(roots) == 0 {
		return func(string) bool { return true }
	}
	seen := map[string]bool{}
	var walk func(n *node)
	walk = func(n *node) {
		if n == nil {
			return
		}
		if ref := n.refName(); ref != "" && !seen[ref] {
			seen[ref] = true
			walk(p.def(ref))
		}
		for _, m := range n.members {
			walk(m.val)
		}
		for _, item := range n.items {
			walk(item)
		}
	}
	for _, r := range roots {
		seen[r] = true
		walk(p.def(r))
	}
	return func(name string) bool { return seen[name] }
}

func goFile(p *protocolDoc, pkg, body, storageImport string) ([]byte, error) {
	src := p.header() + "package " + pkg + "\n\n"
	extra := []string{}
	if regexp.MustCompile(`\bstorage\.[A-Z]`).MatchString(body) {
		extra = append(extra, strconv.Quote(storageImport))
	}
	if regexp.MustCompile(`\bprotocol\.[A-Z]`).MatchString(body) {
		extra = append(extra, strconv.Quote(protocolImport))
	}
	src += goImports(body, extra...) + body
	out, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("%w\n%s", err, src)
	}
	return out, nil
}

var protocolImport = "github.com/runnerq/cloud-storage-go/protocol"

type goParam struct{ name, typ, field string }

func (p *protocolDoc) params(op *node) []goParam {
	var out []goParam
	for _, m := range p.def(p.argsName(op)).get("properties").membersOrNil() {
		out = append(out, goParam{m.key, p.goType(m.val), goField(m.key, m.val)})
	}
	return out
}

func (n *node) membersOrNil() []member {
	if n == nil {
		return nil
	}
	return n.members
}

func (p *protocolDoc) resultType(op *node) string {
	if op.get("result").str("type") == "null" {
		return ""
	}
	return p.goType(op.get("result"))
}

func goSignature(params []goParam, result string) string {
	var ps []string
	for _, prm := range params {
		ps = append(ps, prm.name+" "+prm.typ)
	}
	sig := "(ctx context.Context"
	if len(ps) > 0 {
		sig += ", " + strings.Join(ps, ", ")
	}
	sig += ")"
	if result == "" {
		return sig + " error"
	}
	return sig + " (" + result + ", error)"
}

func generated(op *node) bool {
	v := op.get("x-go-generate")
	return v == nil || v.value != false
}

// goClient is the adapter's method per operation, each a call to the data
// plane.
func goClient(p *protocolDoc, pkg, storageImport string) ([]byte, error) {
	var body bytes.Buffer
	for _, op := range p.ops {
		if !generated(op) {
			continue
		}
		name, params, result := op.str("name"), p.params(op), p.resultType(op)
		var fields []string
		for _, prm := range params {
			fields = append(fields, prm.field+": "+prm.name)
		}
		args := "protocol." + p.argsName(op) + "{" + strings.Join(fields, ", ") + "}"
		fmt.Fprintf(&body, "// %s calls the data plane's %s.\nfunc (b *CloudBackend) %s%s {\n", name, name, name, goSignature(params, result))
		if result == "" {
			fmt.Fprintf(&body, "\treturn b.call(ctx, %q, %s, nil)\n}\n\n", name, args)
		} else {
			fmt.Fprintf(&body, "\tvar out %s\n\terr := b.call(ctx, %q, %s, &out)\n\treturn out, err\n}\n\n", result, name, args)
		}
	}
	return goFile(p, pkg, body.String(), storageImport)
}

// goServer is the data plane's dispatch: decode, validate as the schema
// constrains, call the backend.
func goServer(p *protocolDoc, pkg, storageImport string) ([]byte, error) {
	var body bytes.Buffer
	var ifaces []string
	readers := []*node{}
	for _, op := range p.ops {
		iface := op.str("x-go-interface")
		if iface == "" {
			continue
		}
		if iface == "storagetest.Reader" {
			readers = append(readers, op)
			iface = "reader"
		} else {
			iface = "storage." + iface
		}
		if !slices.Contains(ifaces, iface) {
			ifaces = append(ifaces, iface)
		}
	}
	if len(readers) > 0 {
		body.WriteString("// reader is the read side the conformance suite checks through (storagetest.Reader).\ntype reader interface {\n")
		for _, op := range readers {
			fmt.Fprintf(&body, "\t%s%s\n", op.str("name"), goSignature(p.params(op), p.resultType(op)))
		}
		body.WriteString("}\n\n")
	}
	body.WriteString("// Backend is everything the operations call.\ntype Backend interface {\n")
	for _, i := range ifaces {
		fmt.Fprintf(&body, "\t%s\n", i)
	}
	body.WriteString("}\n\n")

	v := &validators{p: p, funcs: map[string]bool{}}
	body.WriteString("func dispatch(ctx context.Context, b Backend, method string, body json.RawMessage) (any, error) {\n\tswitch method {\n")
	for _, op := range p.ops {
		if !generated(op) {
			continue
		}
		name, args := op.str("name"), p.argsName(op)
		fmt.Fprintf(&body, "\tcase %q:\n\t\tvar a protocol.%s\n\t\tif err := decode(body, &a); err != nil {\n\t\t\treturn nil, err\n\t\t}\n", name, args)
		var call []string
		for _, m := range p.def(args).get("properties").membersOrNil() {
			field := "a." + goField(m.key, m.val)
			for _, check := range v.checks(field, m.key, m.val) {
				body.WriteString("\t\t" + check + "\n")
			}
			arg := field
			if clamp, ok := m.val.num("x-server-clamp"); ok {
				arg = fmt.Sprintf("min(%s, %s(%s))", field, p.goType(m.val), clamp)
			}
			call = append(call, arg)
		}
		callExpr := "b." + name + "(" + strings.Join(append([]string{"ctx"}, call...), ", ") + ")"
		if p.resultType(op) == "" {
			fmt.Fprintf(&body, "\t\treturn nil, %s\n", callExpr)
		} else {
			fmt.Fprintf(&body, "\t\treturn %s\n", callExpr)
		}
	}
	body.WriteString("\tdefault:\n\t\treturn nil, &storage.StorageError{Kind: storage.ErrUnsupported, Message: \"unsupported storage operation\"}\n\t}\n}\n")
	for _, name := range v.order {
		body.WriteString("\n" + v.bodies[name])
	}
	return goFile(p, pkg, body.String(), storageImport)
}

// validators turns schema constraints into Go checks, writing a function
// per constrained definition.
type validators struct {
	p      *protocolDoc
	funcs  map[string]bool
	order  []string
	bodies map[string]string
}

const nilUUID = "00000000-0000-0000-0000-000000000000"

// typeBounds are the bounds a Go integer type already enforces, so checks
// for them are skipped (and would not compile).
var typeBounds = map[string][2]float64{
	"uint16": {0, math.MaxUint16},
	"uint32": {0, math.MaxUint32},
	"uint64": {0, math.MaxFloat64},
}

func (v *validators) checks(expr, label string, s *node) []string {
	fail := func(cond, msg string) string {
		return fmt.Sprintf("if %s {\n\t\t\treturn nil, invalid(%q)\n\t\t}", cond, msg)
	}
	var out []string
	if ref := s.refName(); ref != "" {
		if s.flag("x-go-pointer") {
			out = append(out, fail(expr+" == nil", label+" is required"))
		}
		if fn := v.validator(ref); fn != "" {
			arg := expr
			if !s.flag("x-go-pointer") {
				arg = "&" + expr
			}
			out = append(out, fmt.Sprintf("if err := %s(%s); err != nil {\n\t\t\treturn nil, err\n\t\t}", fn, arg))
		}
	}
	out = append(out, v.bounds(expr, label, s, fail)...)
	if inner := s.nonNull(); inner != nil {
		out = append(out, v.bounds(expr, label, inner, fail)...)
	}
	return out
}

func (v *validators) bounds(expr, label string, s *node, fail func(cond, msg string) string) []string {
	var out []string
	goType := ""
	if s.get("$ref") == nil && s.nonNull() == nil {
		goType = v.p.goType(s)
	} else if ref := s.refName(); ref != "" {
		goType = v.p.def(ref).str("x-go-type")
	}
	tb, typed := typeBounds[goType]
	if not := s.get("not"); not != nil {
		if c := not.get("const"); c != nil && c.value == nilUUID {
			out = append(out, fail(expr+" == uuid.Nil", label+" is required"))
		}
	}
	minL, hasMinL := s.num("minLength")
	maxL, hasMaxL := s.num("maxLength")
	switch {
	case hasMinL && hasMaxL:
		out = append(out, fail(fmt.Sprintf("len(%s) < %s || len(%s) > %s", expr, minL, expr, maxL), fmt.Sprintf("%s must be %s to %s bytes", label, minL, maxL)))
	case hasMaxL:
		out = append(out, fail(fmt.Sprintf("len(%s) > %s", expr, maxL), fmt.Sprintf("%s must be at most %s bytes", label, maxL)))
	case hasMinL:
		out = append(out, fail(fmt.Sprintf("len(%s) < %s", expr, minL), fmt.Sprintf("%s must be at least %s bytes", label, minL)))
	}
	minV, hasMin := s.num("minimum")
	maxV, hasMax := s.num("maximum")
	if typed {
		if f, _ := minV.Float64(); hasMin && f <= tb[0] {
			hasMin = false
		}
		if f, _ := maxV.Float64(); hasMax && f >= tb[1] {
			hasMax = false
		}
	}
	// Durations read as such in messages: 24h0m0s, not nanoseconds.
	show := func(n json.Number) string {
		if i, err := n.Int64(); err == nil && goType == "time.Duration" {
			return time.Duration(i).String()
		}
		return n.String()
	}
	switch {
	case hasMin && hasMax:
		out = append(out, fail(fmt.Sprintf("%s < %s || %s > %s", expr, minV, expr, maxV), fmt.Sprintf("%s must be between %s and %s", label, show(minV), show(maxV))))
	case hasMin:
		out = append(out, fail(fmt.Sprintf("%s < %s", expr, minV), fmt.Sprintf("%s must be at least %s", label, show(minV))))
	case hasMax:
		out = append(out, fail(fmt.Sprintf("%s > %s", expr, maxV), fmt.Sprintf("%s must be at most %s", label, show(maxV))))
	}
	if maxI, ok := s.num("maxItems"); ok {
		out = append(out, fail(fmt.Sprintf("len(%s) > %s", expr, maxI), fmt.Sprintf("%s must have at most %s items", label, maxI)))
	}
	if items := s.get("items"); items != nil {
		if inner := v.bounds("item", label+" item", items, fail); len(inner) > 0 {
			out = append(out, "for _, item := range "+expr+" {\n"+strings.Join(inner, "\n")+"\n}")
		}
	}
	return out
}

// validator is the name of the function checking definition ref, written
// on first use, or "" when the definition has no constraints.
func (v *validators) validator(ref string) string {
	fn := "validate" + ref
	if done, seen := v.funcs[ref]; seen {
		if done {
			return fn
		}
		return ""
	}
	v.funcs[ref] = false
	d := v.p.def(ref)
	var checks []string
	for _, m := range d.get("properties").membersOrNil() {
		for _, c := range v.checks("v."+goField(m.key, m.val), lowerFirst(ref)+"."+m.key, m.val) {
			checks = append(checks, strings.ReplaceAll(c, "return nil, ", "return "))
		}
	}
	if len(checks) == 0 {
		return ""
	}
	v.funcs[ref] = true
	if v.bodies == nil {
		v.bodies = map[string]string{}
	}
	v.order = append(v.order, ref)
	v.bodies[ref] = fmt.Sprintf("func %s(v *%s) error {\n%s\nreturn nil\n}\n", fn, v.p.goType(&node{isObj: true, members: []member{{"$ref", &node{value: "#/$defs/" + ref}}}}), strings.Join(checks, "\n"))
	return fn
}

// tsProtocol is the TypeScript types for the definitions (those reachable
// from roots, when given), and the operations' or messages' map.
func tsProtocol(p *protocolDoc, prefix string, roots ...string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(p.header())
	keep := p.reachable(roots)
	if p.ops != nil {
		fmt.Fprintf(&b, "/** The RunnerQ-Storage-Version header's value. */\nexport const %sVersion = %q;\n\n", prefix, p.version)
	}
	if p.msgs != nil && len(roots) == 0 {
		fmt.Fprintf(&b, "/** The protocol version these types are. */\nexport const %sVersion = %s;\n\n", prefix, p.version)
	}
	if len(p.errorCodes) > 0 {
		b.WriteString("/** The wire codes of the storage error kinds, indexed by kind number. */\nexport const errorCodes = [\n")
		for _, c := range p.errorCodes {
			fmt.Fprintf(&b, "  %q,\n", c)
		}
		b.WriteString("] as const;\n\n")
	}
	for _, m := range p.defs.members {
		if !keep(m.key) {
			continue
		}
		d := m.val
		if desc := d.str("description"); desc != "" {
			writeJSDoc(&b, "", desc)
		}
		if d.str("type") == "object" && d.get("properties") != nil {
			props := d.get("properties").members
			if len(props) == 0 && !d.flag("additionalProperties") {
				fmt.Fprintf(&b, "export type %s = Record<string, never>;\n\n", m.key)
				continue
			}
			required := d.strings("required")
			fmt.Fprintf(&b, "export interface %s {\n", m.key)
			for _, prop := range props {
				if desc := prop.val.str("description"); desc != "" {
					writeJSDoc(&b, "  ", desc)
				}
				opt := ""
				if !slices.Contains(required, prop.key) {
					opt = "?"
				}
				fmt.Fprintf(&b, "  %s%s: %s;\n", prop.key, opt, p.tsType(prop.val))
			}
			if d.flag("additionalProperties") {
				b.WriteString("  [key: string]: unknown;\n")
			}
			b.WriteString("}\n\n")
			continue
		}
		fmt.Fprintf(&b, "export type %s = %s;\n\n", m.key, p.tsType(d))
		if values := d.strings("enum"); len(values) > 0 && d.str("type") == "string" {
			fmt.Fprintf(&b, "/** Every %s. */\nexport const %sValues = [", m.key, lowerFirst(m.key))
			for i, v := range values {
				if i > 0 {
					b.WriteString(", ")
				}
				b.WriteString(strconv.Quote(v))
			}
			fmt.Fprintf(&b, "] as const;\n\n")
		}
	}
	if p.msgs != nil && len(roots) == 0 {
		b.WriteString("/** Each message's kind, sender, data and (for requests) response. */\nexport interface Messages {\n")
		for _, m := range p.msgs {
			resp := "never"
			if r := m.str("response"); r != "" {
				resp = strings.TrimPrefix(r, "#/$defs/")
			}
			fmt.Fprintf(&b, "  %q: {\n    kind: %q;\n    from: %q;\n    data: %s;\n    response: %s;\n  };\n", m.str("type"), m.str("kind"), m.str("from"), strings.TrimPrefix(m.str("data"), "#/$defs/"), resp)
		}
		b.WriteString("}\n")
	}
	if p.ops != nil {
		b.WriteString("/** Each operation's arguments and result. */\nexport interface Operations {\n")
		for _, op := range p.ops {
			fmt.Fprintf(&b, "  %s: { args: %s; result: %s };\n", op.str("name"), p.argsName(op), p.tsType(op.get("result")))
		}
		b.WriteString("}\n\n/** Every message type. */\nexport type MessageType = keyof Messages;\n")
	}
	return bytes.TrimRight(b.Bytes(), "\n"), nil
}

func (p *protocolDoc) tsType(s *node) string {
	if ref := s.refName(); ref != "" {
		return ref
	}
	if enum := s.get("enum"); enum != nil {
		var vs []string
		for _, e := range enum.items {
			if str, ok := e.value.(string); ok {
				vs = append(vs, strconv.Quote(str))
			} else {
				vs = append(vs, fmt.Sprint(e.value))
			}
		}
		return strings.Join(vs, " | ")
	}
	if inner := s.nonNull(); inner != nil {
		return p.tsType(inner) + " | null"
	}
	switch s.str("type") {
	case "string":
		return "string"
	case "boolean":
		return "boolean"
	case "number", "integer":
		return "number"
	case "null":
		return "null"
	case "array":
		t := p.tsType(s.get("items"))
		if strings.Contains(t, " ") {
			t = "(" + t + ")"
		}
		return t + "[]"
	case "object":
		if ap := s.get("additionalProperties"); ap != nil && ap.isObj {
			return "Record<string, " + p.tsType(ap) + ">"
		}
		if s.flag("additionalProperties") {
			var fields []string
			for _, m := range s.get("properties").membersOrNil() {
				fields = append(fields, m.key+"?: "+p.tsType(m.val))
			}
			return "{ " + strings.Join(append(fields, "[key: string]: unknown"), "; ") + " }"
		}
	}
	return "unknown"
}

// isObjectRef reports whether s refers to an object definition (one that
// becomes a struct).
func (p *protocolDoc) isObjectRef(s *node) bool {
	ref := s.refName()
	if ref == "" {
		return false
	}
	d := p.def(ref)
	return d.str("type") == "object" && d.str("x-go-type") == ""
}

// goEnumConst is an enum value's Go constant: x-go-names, else the prefix
// and the value in PascalCase.
func goEnumConst(d *node, i int, value string) string {
	if names := d.strings("x-go-names"); i < len(names) {
		return names[i]
	}
	return d.str("x-go-prefix") + goField(value, &node{})
}

// goConductor is the conductor protocol's Go types: Version, the message
// types, a typed string per enum and a struct per object definition.
func goConductor(p *protocolDoc, pkg string) ([]byte, error) {
	var body bytes.Buffer
	fmt.Fprintf(&body, "// Version is the protocol version these types are.\nconst Version = %s\n\n", p.version)
	body.WriteString("// Message types.\nconst (\n")
	for _, m := range p.msgs {
		t := m.str("type")
		name := "Type" + goField(strings.NewReplacer(".", "_").Replace(t), &node{})
		if desc := m.str("description"); desc != "" {
			writeComment(&body, "\t", "// ", desc)
		}
		fmt.Fprintf(&body, "\t%s = %q\n", name, t)
	}
	body.WriteString(")\n\n")
	all := func(string) bool { return true }
	p.goEnums(&body, all)
	p.goStructs(&body, p.generatedDefs(all))
	return goFile(p, pkg, body.String(), "")
}

// goEnums writes a typed string, and a constant per value, for each string
// enum keep selects.
func (p *protocolDoc) goEnums(body *bytes.Buffer, keep func(string) bool) {
	for _, m := range p.defs.members {
		d := m.val
		values := d.strings("enum")
		if d.str("type") != "string" || len(values) == 0 || !keep(m.key) {
			continue
		}
		writeComment(body, "", "// ", m.key+" is "+lowerFirst(d.str("description")))
		fmt.Fprintf(body, "type %s string\n\nconst (\n", m.key)
		for i, v := range values {
			fmt.Fprintf(body, "\t%s %s = %q\n", goEnumConst(d, i, v), m.key, v)
		}
		body.WriteString(")\n\n")
	}
}

// tsSpecs is a decode spec (the TypeScript SDK's Spec: "string", "int",
// "number", "bool", "any", {array}, {object}, or a thunk) per object
// definition, so request decoding rejects unknown fields as Go's does.
// Maps decode as "any".
func tsSpecs(p *protocolDoc, specImport string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(p.header())
	fmt.Fprintf(&b, "import type { Spec } from %q;\n\n", specImport)
	var names []string
	for _, m := range p.defs.members {
		if m.val.str("type") == "object" && m.val.get("properties") != nil {
			names = append(names, strconv.Quote(m.key))
		}
	}
	fmt.Fprintf(&b, "/** The definitions with a decode spec. */\nexport type SpecName =\n  | %s;\n\n", strings.Join(names, "\n  | "))
	b.WriteString("/** A decode spec per object definition. */\nexport const specs: Record<SpecName, Spec> = {\n")
	for _, m := range p.defs.members {
		if m.val.str("type") == "object" && m.val.get("properties") != nil {
			fmt.Fprintf(&b, "  %s: %s,\n", m.key, p.tsSpec(m.val, true))
		}
	}
	b.WriteString("};\n")
	return b.Bytes(), nil
}

func (p *protocolDoc) tsSpec(s *node, top bool) string {
	if ref := s.refName(); ref != "" && !top {
		d := p.def(ref)
		if d.str("type") == "object" && d.get("properties") != nil {
			return fmt.Sprintf("() => specs.%s", ref)
		}
		return p.tsSpec(d, false)
	}
	if inner := s.nonNull(); inner != nil {
		return p.tsSpec(inner, false)
	}
	switch s.str("type") {
	case "string":
		return `"string"`
	case "boolean":
		return `"bool"`
	case "number":
		return `"number"`
	case "integer":
		return `"int"`
	case "array":
		return "{ array: " + p.tsSpec(s.get("items"), false) + " }"
	case "object":
		props := s.get("properties")
		if props == nil || s.get("additionalProperties") != nil && s.get("additionalProperties").value != false {
			return `"any"`
		}
		var fields []string
		for _, m := range props.members {
			fields = append(fields, m.key+": "+p.tsSpec(m.val, false))
		}
		return "{ object: { " + strings.Join(fields, ", ") + " } }"
	}
	return `"any"`
}
