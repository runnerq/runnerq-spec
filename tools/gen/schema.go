package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

type schema struct {
	Migrations []migration
	Concurrent []concurrentIndex
	Catalog    catalog
}

type migration struct{ Name, SQL string }

type concurrentIndex struct {
	Name     string `json:"name"`
	Table    string `json:"table"`
	Replaces string `json:"replaces"`
	Doc      string `json:"doc"`
	SQL      string `json:"sql"`
}

type catalog struct {
	Description string `json:"description"`
	Tables      []struct {
		Name    string `json:"name"`
		Columns []struct {
			Name     string  `json:"name"`
			Type     string  `json:"type"`
			Nullable bool    `json:"nullable"`
			Default  *string `json:"default"`
		} `json:"columns"`
		PrimaryKey []string `json:"primary_key"`
	} `json:"tables"`
	Indexes []struct {
		Name       string `json:"name"`
		Table      string `json:"table"`
		Definition string `json:"definition"`
	} `json:"indexes"`
	Retired struct {
		Columns []string `json:"columns"`
		Indexes []string `json:"indexes"`
	} `json:"retired"`
}

const schemaHeader = "Code generated by runnerq-spec tools/gen from schema/postgres. DO NOT EDIT."

func loadSchema(root string) (*schema, error) {
	dir := filepath.Join(root, "schema", "postgres")
	files, err := filepath.Glob(filepath.Join(dir, "migrations", "*.sql"))
	if err != nil {
		return nil, err
	}
	slices.Sort(files)
	var s schema
	for _, f := range files {
		sql, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		s.Migrations = append(s.Migrations, migration{strings.TrimSuffix(filepath.Base(f), ".sql"), string(sql)})
	}
	if len(s.Migrations) == 0 {
		return nil, fmt.Errorf("no migrations in %s", dir)
	}
	var ci struct {
		Description string            `json:"description"`
		Indexes     []concurrentIndex `json:"indexes"`
	}
	if err := strictJSON(filepath.Join(dir, "concurrent_indexes.json"), &ci); err != nil {
		return nil, err
	}
	s.Concurrent = ci.Indexes
	if err := strictJSON(filepath.Join(dir, "catalog.json"), &s.Catalog); err != nil {
		return nil, err
	}
	return &s, nil
}

func strictJSON(path string, v any) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	if err := dec.Decode(v); err != nil {
		return fmt.Errorf("%s: %w", filepath.Base(path), err)
	}
	return nil
}

func goSchema(s *schema, pkg string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\npackage %s\n\n", schemaHeader, pkg)
	b.WriteString(`// PostgresMigration is one schema migration. Every migration is safe to
// re-run; they run in order, in one transaction.
type PostgresMigration struct {
	Name string
	SQL  string
}

// PostgresConcurrentIndex is built with CREATE INDEX CONCURRENTLY after the
// migrations, outside any transaction: drop it if invalid, build it if
// missing, then drop Replaces.
type PostgresConcurrentIndex struct {
	Name     string
	Table    string
	Replaces string
	SQL      string
}

// CatalogColumn is a column as information_schema reports it. Default is ""
// when the column has none.
type CatalogColumn struct {
	Name     string
	Type     string
	Nullable bool
	Default  string
}

// CatalogTable is a table, its columns and its primary key.
type CatalogTable struct {
	Name       string
	Columns    []CatalogColumn
	PrimaryKey []string
}

// CatalogIndex is an index other than a primary key, as pg_get_indexdef
// renders it without the schema.
type CatalogIndex struct {
	Name       string
	Table      string
	Definition string
}

// Catalog is what the migrations and concurrent indexes produce. Retired
// objects must not exist.
type Catalog struct {
	Tables         []CatalogTable
	Indexes        []CatalogIndex
	RetiredColumns []string // table.column
	RetiredIndexes []string
}

// PostgresMigrations run in order.
var PostgresMigrations = []PostgresMigration{
`)
	for _, m := range s.Migrations {
		fmt.Fprintf(&b, "\t{Name: %q, SQL: %s},\n", m.Name, goString(m.SQL))
	}
	b.WriteString("}\n\n// PostgresConcurrentIndexes are built in order after the migrations.\nvar PostgresConcurrentIndexes = []PostgresConcurrentIndex{\n")
	for _, c := range s.Concurrent {
		fmt.Fprintf(&b, "\t{Name: %q, Table: %q, Replaces: %q, SQL: %s},\n", c.Name, c.Table, c.Replaces, goString(c.SQL))
	}
	b.WriteString("}\n\n// PostgresCatalog is schema/postgres/catalog.json.\nvar PostgresCatalog = Catalog{\n\tTables: []CatalogTable{\n")
	for _, t := range s.Catalog.Tables {
		fmt.Fprintf(&b, "\t\t{Name: %q, PrimaryKey: %s, Columns: []CatalogColumn{\n", t.Name, goStrings(t.PrimaryKey))
		for _, c := range t.Columns {
			def := ""
			if c.Default != nil {
				def = *c.Default
			}
			fmt.Fprintf(&b, "\t\t\t{Name: %q, Type: %q, Nullable: %v, Default: %q},\n", c.Name, c.Type, c.Nullable, def)
		}
		b.WriteString("\t\t}},\n")
	}
	b.WriteString("\t},\n\tIndexes: []CatalogIndex{\n")
	for _, i := range s.Catalog.Indexes {
		fmt.Fprintf(&b, "\t\t{Name: %q, Table: %q, Definition: %q},\n", i.Name, i.Table, i.Definition)
	}
	fmt.Fprintf(&b, "\t},\n\tRetiredColumns: %s,\n\tRetiredIndexes: %s,\n}\n", goStrings(s.Catalog.Retired.Columns), goStrings(s.Catalog.Retired.Indexes))
	return format.Source(b.Bytes())
}

// goString is a raw string literal when the text allows one.
func goString(s string) string {
	if !strings.Contains(s, "`") {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}

func goStrings(list []string) string {
	q := make([]string, len(list))
	for i, s := range list {
		q[i] = strconv.Quote(s)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

func tsSchema(s *schema) ([]byte, error) {
	type tsMigration struct {
		Name string `json:"name"`
		SQL  string `json:"sql"`
	}
	type tsIndex struct {
		Name     string `json:"name"`
		Table    string `json:"table"`
		Replaces string `json:"replaces"`
		SQL      string `json:"sql"`
	}
	var ms []tsMigration
	for _, m := range s.Migrations {
		ms = append(ms, tsMigration{m.Name, m.SQL})
	}
	var is []tsIndex
	for _, c := range s.Concurrent {
		is = append(is, tsIndex{c.Name, c.Table, c.Replaces, c.SQL})
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\n", schemaHeader)
	b.WriteString(`/** One schema migration. Every migration is safe to re-run; they run in order, in one transaction. */
export interface PostgresMigration {
  name: string;
  sql: string;
}
/** Built CONCURRENTLY after the migrations, outside any transaction: drop it if invalid, build it if missing, then drop replaces. */
export interface PostgresConcurrentIndex {
  name: string;
  table: string;
  replaces: string;
  sql: string;
}
/** What the migrations and concurrent indexes produce; retired objects must not exist. */
export interface Catalog {
  description: string;
  tables: {
    name: string;
    columns: {
      name: string;
      type: string;
      nullable: boolean;
      default: string | null;
    }[];
    primary_key: string[];
  }[];
  indexes: { name: string; table: string; definition: string }[];
  retired: { columns: string[]; indexes: string[] };
}
`)
	for _, part := range []struct {
		name, typ, doc string
		v              any
	}{
		{"postgresMigrations", "readonly PostgresMigration[]", "Run in order.", ms},
		{"postgresConcurrentIndexes", "readonly PostgresConcurrentIndex[]", "Built in order after the migrations.", is},
		{"postgresCatalog", "Catalog", "schema/postgres/catalog.json.", s.Catalog},
	} {
		raw, err := json.MarshalIndent(part.v, "", "  ")
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "/** %s */\nexport const %s: %s = %s;\n", part.doc, part.name, part.typ, raw)
	}
	return b.Bytes(), nil
}
