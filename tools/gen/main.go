// Command gen writes the spec's constants, or its Postgres schema
// (-part schema), as Go or TypeScript source.
//
//	go run ./tools/gen -lang go -pkg spec -out ../internal/spec/spec.go
//	go run ./tools/gen -lang go -pkg spec -part schema -out ../internal/spec/schema.go
//	go run ./tools/gen -lang ts -out ../src/spec.ts
//	go run ./tools/gen -lang ts -part schema -out ../src/spec-schema.ts
//
// Run it from the spec root (the default -root).
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

type spec struct {
	Version   string
	Constants []constant `json:"constants"`
	Enums     []enum     `json:"enums"`
}

type constant struct {
	Name  string `json:"name"`
	Type  string `json:"type"` // "string", "int" (fits a JavaScript number) or "int64"; values are strings
	Value string `json:"value"`
	Doc   string `json:"doc"`
}

type enum struct {
	Name   string `json:"name"`
	Doc    string `json:"doc"`
	Values []struct {
		Name  string `json:"name"`
		Value int    `json:"value"`
	} `json:"values"`
}

func main() {
	root := flag.String("root", ".", "spec root")
	lang := flag.String("lang", "", "go or ts")
	pkg := flag.String("pkg", "spec", "Go package name")
	out := flag.String("out", "", "output file")
	part := flag.String("part", "constants", "constants or schema")
	flag.Parse()
	if *out == "" {
		fail(fmt.Errorf("-out is required"))
	}
	var src []byte
	var err error
	switch *part {
	case "constants":
		var s *spec
		if s, err = load(*root); err == nil {
			switch *lang {
			case "go":
				src, err = goSource(s, *pkg)
			case "ts":
				src, err = tsSource(s)
			default:
				err = fmt.Errorf("-lang must be go or ts")
			}
		}
	case "schema":
		var s *schema
		if s, err = loadSchema(*root); err == nil {
			switch *lang {
			case "go":
				src, err = goSchema(s, *pkg)
			case "ts":
				src, err = tsSchema(s)
			default:
				err = fmt.Errorf("-lang must be go or ts")
			}
		}
	default:
		err = fmt.Errorf("-part must be constants or schema")
	}
	if err != nil {
		fail(err)
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fail(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}

func load(root string) (*spec, error) {
	version, err := os.ReadFile(filepath.Join(root, "VERSION"))
	if err != nil {
		return nil, err
	}
	raw, err := os.ReadFile(filepath.Join(root, "constants", "constants.json"))
	if err != nil {
		return nil, err
	}
	var s spec
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&s); err != nil {
		return nil, fmt.Errorf("constants.json: %w", err)
	}
	s.Version = strings.TrimSpace(string(version))
	seen := map[string]bool{}
	for _, c := range s.Constants {
		if c.Name == "" || seen[c.Name] || c.Doc == "" {
			return nil, fmt.Errorf("constant %q: needs a unique name and a doc", c.Name)
		}
		seen[c.Name] = true
		switch c.Type {
		case "string":
		case "int64":
			if _, err := strconv.ParseInt(c.Value, 10, 64); err != nil {
				return nil, fmt.Errorf("constant %q: %w", c.Name, err)
			}
		case "int":
			if n, err := strconv.ParseInt(c.Value, 10, 64); err != nil || n > 1<<53 || n < -(1<<53) {
				return nil, fmt.Errorf("constant %q: not an integer a JavaScript number holds exactly", c.Name)
			}
		default:
			return nil, fmt.Errorf("constant %q: unknown type %q", c.Name, c.Type)
		}
	}
	for _, e := range s.Enums {
		if e.Name == "" || seen[e.Name] || e.Doc == "" || len(e.Values) == 0 {
			return nil, fmt.Errorf("enum %q: needs a unique name, a doc and values", e.Name)
		}
		seen[e.Name] = true
	}
	return &s, nil
}

const header = "Code generated by runnerq-spec tools/gen from constants/constants.json. DO NOT EDIT."

func goSource(s *spec, pkg string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\n", header)
	fmt.Fprintf(&b, "// Package %s holds the constants every RunnerQ implementation shares\n// (github.com/runnerq/runnerq-spec).\npackage %s\n\n", pkg, pkg)
	fmt.Fprintf(&b, "// Version is the runnerq-spec release these constants come from.\nconst Version = %q\n", s.Version)
	for _, c := range s.Constants {
		name := goName(c.Name)
		b.WriteString("\n")
		writeComment(&b, "", "// ", name+" is "+lowerFirst(c.Doc))
		switch c.Type {
		case "int64":
			fmt.Fprintf(&b, "const %s int64 = %s\n", name, c.Value)
		case "int":
			fmt.Fprintf(&b, "const %s = %s\n", name, c.Value)
		default:
			fmt.Fprintf(&b, "const %s = %q\n", name, c.Value)
		}
	}
	for _, e := range s.Enums {
		prefix := goName(e.Name)
		b.WriteString("\n")
		writeComment(&b, "", "// ", e.Doc)
		b.WriteString("const (\n")
		for _, v := range e.Values {
			fmt.Fprintf(&b, "\t%s%s = %d\n", prefix, goName(v.Name), v.Value)
		}
		b.WriteString(")\n")
	}
	return format.Source(b.Bytes())
}

func tsSource(s *spec) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\n", header)
	fmt.Fprintf(&b, "/** The runnerq-spec release these constants come from. */\nexport const specVersion = %s;\n", quoteTS(s.Version))
	for _, c := range s.Constants {
		b.WriteString("\n")
		doc := c.Doc
		if c.Type == "int64" {
			doc += " A decimal string: it does not fit a JavaScript number."
		}
		writeJSDoc(&b, "", doc)
		value := quoteTS(c.Value)
		if c.Type == "int" {
			value = c.Value
		}
		fmt.Fprintf(&b, "export const %s = %s;\n", tsName(c.Name), value)
	}
	for _, e := range s.Enums {
		b.WriteString("\n")
		writeJSDoc(&b, "", e.Doc)
		fmt.Fprintf(&b, "export const %s = {\n", tsName(e.Name))
		for _, v := range e.Values {
			fmt.Fprintf(&b, "  %s: %d,\n", v.Name, v.Value)
		}
		b.WriteString("} as const;\n")
	}
	return b.Bytes(), nil
}

// initialisms keeps Go names like SerializationJSON in Go style.
var initialisms = map[string]string{"id": "ID", "json": "JSON", "superjson": "SuperJSON"}

func goName(snake string) string {
	var b strings.Builder
	for _, w := range strings.Split(snake, "_") {
		if up, ok := initialisms[w]; ok {
			b.WriteString(up)
		} else if w != "" {
			b.WriteString(strings.ToUpper(w[:1]) + w[1:])
		}
	}
	return b.String()
}

func tsName(snake string) string {
	words := strings.Split(snake, "_")
	for i := 1; i < len(words); i++ {
		if w := words[i]; w != "" {
			words[i] = strings.ToUpper(w[:1]) + w[1:]
		}
	}
	return strings.Join(words, "")
}

func lowerFirst(s string) string {
	if s == "" || (len(s) > 1 && s[1] >= 'A' && s[1] <= 'Z') {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

// quoteTS writes a double-quoted TypeScript string, as Prettier formats it.
func quoteTS(s string) string {
	q, _ := json.Marshal(s)
	return string(q)
}

func wrap(text string, width int) []string {
	var lines []string
	line := ""
	for _, w := range strings.Fields(text) {
		if line != "" && len(line)+1+len(w) > width {
			lines = append(lines, line)
			line = w
		} else if line == "" {
			line = w
		} else {
			line += " " + w
		}
	}
	return append(lines, line)
}

func writeComment(b *bytes.Buffer, indent, marker, text string) {
	for _, l := range wrap(text, 76-len(indent)) {
		b.WriteString(indent + marker + l + "\n")
	}
}

func writeJSDoc(b *bytes.Buffer, indent, text string) {
	lines := wrap(text, 76-len(indent))
	if len(lines) == 1 && len(lines[0]) <= 70 {
		fmt.Fprintf(b, "%s/** %s */\n", indent, lines[0])
		return
	}
	b.WriteString(indent + "/**\n")
	for _, l := range lines {
		b.WriteString(indent + " * " + l + "\n")
	}
	b.WriteString(indent + " */\n")
}
